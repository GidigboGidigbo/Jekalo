import { z } from "zod";
import { registry } from "../registry.js";
import { registerError, errorSchema, uuidField, dateTimeField, moneyKobo } from "./common.js";

registerError();

export const paymentSchema = z
  .object({
    id: uuidField("Payment ID."),
    userId: uuidField("Payer's user ID."),
    purpose: z.enum(["ride", "rental"]).describe("What the charge was for."),
    rentalBookingId: uuidField("Rental booking ID.").nullish(),
    rideBookingId: uuidField("Ride booking ID.").nullish(),
    reference: z.string().describe("Payment reference, generated by us (idempotency key)."),
    amount: moneyKobo("Charge amount."),
    platformPercentage: z.number().describe("Commission percentage snapshotted at charge time."),
    platformFee: moneyKobo("Platform fee snapshotted at charge time."),
    status: z
      .enum(["pending", "success", "failed", "abandoned"])
      .describe(
        "One row per Paystack transaction attempt; reversal is a ledger entry, not this status.",
      ),
    channel: z.string().nullish().describe("Paystack payment channel."),
    gatewayResponse: z.string().nullish().describe("Gateway response text."),
    paidAt: dateTimeField("When the charge was paid.").nullish(),
    createdAt: dateTimeField("First recorded time."),
    updatedAt: dateTimeField("Last update time."),
  })
  .openapi("Payment", {
    description: "A Paystack transaction attempt for a ride or rental.",
  });
registry.register("Payment", paymentSchema);

registry.registerPath({
  method: "post",
  path: "/payments/webhook",
  operationId: "paystackWebhook",
  summary: "Paystack webhook (charge/transfer/refund events)",
  description:
    "Receives Paystack event payloads. The raw request body is HMAC-SHA512 verified against " +
    "x-paystack-signature before processing; unverified requests are dropped with 401. " +
    "Always respond 200 to acknowledged webhooks.",
  tags: ["Payments"],
  request: {
    headers: z.object({
      "x-paystack-signature": z.string().openapi({
        param: { description: "Paystack signature header (HMAC-SHA512 of the raw body)." },
      }),
    }),
  },
  responses: {
    200: { description: "Webhook acknowledged. No content." },
    401: {
      description: "Invalid webhook signature.",
      content: { "application/json": { schema: errorSchema } },
    },
  },
});

registry.registerPath({
  method: "get",
  path: "/payments",
  operationId: "listPayments",
  summary: "List the authenticated user's payments",
  tags: ["Payments"],
  security: [{ bearerAuth: [] }],
  responses: {
    200: {
      description: "Payments fetched, newest first.",
      content: { "application/json": { schema: z.array(paymentSchema) } },
    },
    401: {
      description: "Missing or invalid token.",
      content: { "application/json": { schema: errorSchema } },
    },
  },
});

registry.registerPath({
  method: "get",
  path: "/payments/verify/{reference}",
  operationId: "verifyPayment",
  summary: "Verify a payment by reference",
  description:
    "Refreshes the payment status from Paystack and returns the settled row.",
  tags: ["Payments"],
  security: [{ bearerAuth: [] }],
  request: {
    params: z.object({
      reference: z.string().openapi({ param: { description: "Payment reference." } }),
    }),
  },
  responses: {
    200: {
      description: "Payment verified.",
      content: { "application/json": { schema: paymentSchema } },
    },
    401: {
      description: "Missing or invalid token.",
      content: { "application/json": { schema: errorSchema } },
    },
    404: {
      description: "Payment not found.",
      content: { "application/json": { schema: errorSchema } },
    },
    502: {
      description: "Paystack gateway error.",
      content: { "application/json": { schema: errorSchema } },
    },
  },
});